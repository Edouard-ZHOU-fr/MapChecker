OPTS = {"min_overlap_area": 1.0, "parallel_min_length": 10.0, "parallel_min_gap": 1.5, "turn_angle": 30.0,
        "turn_window": 30.0, "only_check_AOI": False}


def write_map(path):
    """
    A road along +x (0 <= x <= 50, 0 <= y <= 3.5), and a crosswalk crossing it (20 <= x <= 24, -2 <= y <= 5.5),
    both ends of the crosswalk extend 2 m beyond the road; all elevations are 0
    """
    points = {1: (0, 3.5), 2: (50, 3.5), 3: (0, 0), 4: (50, 0),
              5: (20, -2), 6: (20, 5.5), 7: (24, -2), 8: (24, 5.5)}
    ways = {11: (1, 2), 12: (3, 4), 13: (5, 6), 14: (7, 8)}
    lanelets = {21: (11, 12, "road", {"speed_limit": "30"}), 22: (13, 14, "crosswalk", {})}
    write_osm(path, points, ways, lanelets)


def write_osm(path, points, ways, lanelets, extra=()):
    """
    points:   {node id: (x, y) or (x, y, ele)}, ele defaults to 0, if None the node has no ele tag
    ways:     {way id: (node id, ...)}
    lanelets: {lanelet id: (left boundary way id, right boundary way id, subtype, other tags
                            [, ids of the referenced regulatory elements])}
    extra:    other XML elements written as is (e.g. stop lines with their tags, regulatory elements)
    """
    lines = ['<?xml version="1.0"?>', '<osm version="0.6">']
    for nid, (x, y, *z) in points.items():
        ele = "" if z and z[0] is None else f'<tag k="ele" v="{z[0] if z else 0}"/>'
        lines.append(f'<node id="{nid}" lat="{48 + y * 1e-5}" lon="{2 + x * 1e-5}">'
                     f'<tag k="local_x" v="{x}"/><tag k="local_y" v="{y}"/>{ele}</node>')
    for wid, refs in ways.items():
        lines.append(f'<way id="{wid}">' + "".join(f'<nd ref="{r}"/>' for r in refs) + "</way>")
    for rid, (left, right, subtype, tags, *regs) in lanelets.items():
        lines.append(f'<relation id="{rid}"><member type="way" role="left" ref="{left}"/>'
                     f'<member type="way" role="right" ref="{right}"/>'
                     + "".join(f'<member type="relation" role="regulatory_element" ref="{r}"/>' for r in (regs or [()])[0])
                     + f'<tag k="type" v="lanelet"/><tag k="subtype" v="{subtype}"/>'
                     + "".join(f'<tag k="{k}" v="{v}"/>' for k, v in tags.items()) + "</relation>")
    lines.extend(extra)
    lines.append("</osm>")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def run_extensions(extensions, map_path, output_prefix=None, ignore=None):
    """
    Run extensions that went through load(), return (Printer, printed text).
    output_prefix: path prefix of the files generated by the extensions (e.g. figures);
    ignore: {check: {lanelet id: reason}} (in check_lanelet_map.py, merged from ignore.yaml and ignore in extension configs)
    """
    out = Printer(False, ignore=ignore)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        extmod.run_extensions(MapContext.from_file(map_path, OPTS, output_prefix), extensions, out)
    return out, buf.getvalue()


class ExtensionTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.map_path = os.path.join(self.tmp, "map.osm")
        write_map(self.map_path)

    def tearDown(self):
        shutil.rmtree(self.tmp)
        if "matplotlib.pyplot" in sys.modules:
            sys.modules["matplotlib.pyplot"].close("all")

    def test_every_extension_loads_and_runs(self):
        """All extensions under ext/ (including _template) load with the default config and run on the synthetic map
        without errors"""
        available = extmod.discover()
        self.assertIn("_template", available)
        for name, ext in available.items():
            with self.subTest(extension=name):
                extmod.load(ext)
                out, text = run_extensions([ext], self.map_path)
                self.assertNotIn("crashed", text)
                self.assertIn(f"=== Ext {name}", text, "the extension should print a header 'Ext <name>: ...'")

    def test_crosswalk(self):
        ext = extmod.load(extmod.discover()["crosswalk"], {"max_extension": 0.5, "ignore": []})
        cw = MapContext.from_file(self.map_path, OPTS)
        exts = ext.module.end_extensions(cw.lanelets["22"], cw.vehicle_near(cw.lanelets["22"].polygon))
        self.assertEqual([e[1] for e in exts], ["21", "21"])
        for length, _, inside in exts:
            self.assertAlmostEqual(length, 2.0, delta=0.02)
            self.assertFalse(inside)
        out, _ = run_extensions([ext], self.map_path)
        self.assertEqual(out.count["crosswalk"], 1)

        ext = extmod.load(extmod.discover()["crosswalk"], {"max_extension": 3.0})
        out, _ = run_extensions([ext], self.map_path)
        self.assertEqual(out.count["crosswalk"], 0)

    def test_stopline(self):
        """stopline: 2 points pass; more points WARNING with the distance of the middle point to the line between the
        ends (also when the points are on the line); 1 point ERROR; ignored by the stop line id or a lanelet using it"""
        path = os.path.join(self.tmp, "stopline.osm")
        points = {1: (0, 3.5), 2: (50, 3.5), 3: (0, 0), 4: (50, 0),
                  31: (10, 0), 32: (10, 3.5),                    # straight line of 2 points
                  33: (30, 0), 34: (30.5, 1.75), 35: (30, 3.5),  # polyline, middle point 0.5 m off the line
                  36: (40, 0), 37: (40, 1.75), 38: (40, 3.5),    # 3 points on a straight line
                  39: (45, 0)}                                   # a single point
        stop_lines = {51: (31, 32), 52: (33, 34, 35), 53: (36, 37, 38), 54: (39,)}
        extra = [f'<way id="{wid}">' + "".join(f'<nd ref="{r}"/>' for r in refs) + '<tag k="type" v="stop_line"/></way>'
                 for wid, refs in stop_lines.items()]
        extra.append('<relation id="61"><member type="way" role="ref_line" ref="52"/>'
                     '<tag k="type" v="regulatory_element"/><tag k="subtype" v="traffic_sign"/></relation>')
        write_osm(path, points, {11: (1, 2), 12: (3, 4)}, {21: (11, 12, "road", {}, [61])}, extra)

        ext = extmod.load(extmod.discover()["stopline"])
        out, text = run_extensions([ext], path)
        self.assertEqual((out.count["stopline"], out.errors["stopline"]), (2, 1), text)
        self.assertIn("stop_line 52: 3 points (polyline), should be a straight line of 2 points; node 34 is 0.50 m "
                      "off the line between its ends (length 3.6 m) | lanelet 21", text)
        self.assertIn("stop_line 53: 3 points (polyline), should be a straight line of 2 points; node 36 is 0.00 m", text)
        self.assertIn("stop_line 54: only 1 point(s), a stop line needs 2", text)
        self.assertNotIn("stop_line 51", text)
        self.assertIn("stop lines not referenced by any regulatory element: 51 53 54", text)

        for ignored in ("52", "21"):  # the stop line itself, or the lanelet referencing it
            with self.subTest(ignored=ignored):
                out, text = run_extensions([ext], path, ignore={"stopline": {ignored: ""}})
                self.assertEqual(out.count["stopline"], 1, text)
                self.assertEqual(out.suppressed[("stopline", ignored)], 1)

    def test_border_sharing(self):
        """border_sharing: side-by-side lanelets whose facing boundaries coincide but are different ways (same
        direction with a gap, opposite directions with an overlap) are reported, a shared boundary is not"""
        path = os.path.join(self.tmp, "border.osm")
        y = {"l51": 3.5, "r51": 0.0, "l52": -0.2, "r52": -3.5, "r53": -7.0, "l54": 3.3, "r54": 7.0}
        points, ways = {}, {}
        for k, (name, yy) in enumerate(y.items()):
            start, end = (50, 0) if name.endswith("54") else (0, 50)  # lanelet 54 goes in the -x direction
            points[100 + 2 * k], points[101 + 2 * k] = (start, yy), (end, yy)
            ways[200 + k] = (100 + 2 * k, 101 + 2 * k)
        w = dict(zip(y, ways))
        lanelets = {51: (w["l51"], w["r51"], "road", {}),
                    52: (w["l52"], w["r52"], "road", {}),   # its own left line 0.2 m right of 51's right: gap
                    53: (w["r52"], w["r53"], "road", {}),   # shares 52's right boundary
                    54: (w["l54"], w["r54"], "road", {})}   # opposite direction, left line 0.2 m inside 51: overlap
        write_osm(path, points, ways, lanelets)

        ext = extmod.load(extmod.discover()["border_sharing"])
        out, text = run_extensions([ext], path)
        self.assertEqual(out.count["border_sharing"], 2, text)
        self.assertIn("lanelet 51 right (way 201) / lanelet 52 left (way 202): boundaries coincide over 50.0 m "
                      "(100% of the shorter) but are different ways, gap 0.20 m between the lanes; they are not "
                      "adjacent in the routing graph", text)
        self.assertIn("lanelet 51 left (way 200) / lanelet 54 left (way 205), opposite directions: boundaries coincide "
                      "over 50.0 m (100% of the shorter) but are different ways, overlap 0.20 m between the lanes", text)
        self.assertIn("3 pairs of side-by-side lanelets: 1 share their boundary, 2 do not", text)

        out, text = run_extensions([ext], path, ignore={"border_sharing": {"54": ""}})
        self.assertEqual(out.count["border_sharing"], 1, text)

        ext = extmod.load(extmod.discover()["border_sharing"], {"max_distance": 0.1})
        out, text = run_extensions([ext], path)
        self.assertEqual(out.count["border_sharing"], 0, text)

    def test_altitude(self):
        """altitude: detection of step / spike / cross slope, nodes without ele, ignore list and trend chart"""
        ext = extmod.load(extmod.discover()["altitude"], {"plot": False})
        pts = np.c_[np.arange(0.0, 60.0, 10.0), np.zeros(6)]
        slope = 0.02 * pts[:, 0]  # 2% slope, adjacent points 10 m apart

        def kinds(offset, min_step=0.1):
            return [(kind, k) for kind, k, *_ in ext.module.slope_points(pts, slope + offset, 0.15, min_step)]

        self.assertEqual(kinds(0.0), [])
        self.assertEqual(kinds(np.r_[0, 0, 2.0, 0, 0, 0]), [("spike", 2)])
        self.assertEqual(kinds(np.r_[0, 0, 0, 2.0, 2.0, 2.0]), [("step", 2)])
        self.assertEqual(kinds(np.r_[0, 0, 0, 2.0, 2.0, 2.0], min_step=3.0), [])
        self.assertEqual(kinds(np.r_[0, 0, np.nan, 0, 0, 0]), [])

        out, _ = run_extensions([ext], self.map_path)  # all elevations are 0
        self.assertEqual(out.count["altitude"], 0)

        # a 50 m long road, the left boundary has a 2 m spike at x = 20 (the opposite point on the right boundary is no
        # longer reported for cross slope), the right boundary point at x = 40 has no ele
        path = os.path.join(self.tmp, "altitude.osm")
        left = {k + 1: (10.0 * k, 3.5, 0.2 * k + (2.0 if k == 2 else 0.0)) for k in range(6)}
        right = {k + 7: (10.0 * k, 0.0, None if k == 4 else 0.2 * k) for k in range(6)}
        write_osm(path, {**left, **right}, {31: tuple(left), 32: tuple(right)}, {41: (31, 32, "road", {})})
        out, text = run_extensions([ext], path)
        self.assertEqual(out.count["altitude"], 2, text)
        self.assertIn("#1 spike at node 3: 2.00 m above nodes 2 and 4", text)
        self.assertIn("lanelet 41: no elevation (ele) on node 11", text)

        # the whole left boundary is 1 m higher than the right one: cross slope 1 / 3.5 = 29%,
        # reported once for the whole lanelet
        left = {nid: (x, y, z + 1.0 if nid != 3 else 1.4) for nid, (x, y, z) in left.items()}
        right = {nid: (x, y, 0.2 * (nid - 7)) for nid, (x, y, _) in right.items()}
        write_osm(path, {**left, **right}, {31: tuple(left), 32: tuple(right)}, {41: (31, 32, "road", {})})
        out, text = run_extensions([ext], path)
        self.assertEqual(out.count["altitude"], 1, text)
        self.assertIn("cross slope at node 1: 1.00 m above the right boundary 3.50 m away (cross slope 29%", text)
        self.assertIn("lanelet 41 left (12 nodes over max)", text)

        ext = extmod.load(extmod.discover()["altitude"], {"ignore": [41]})
        prefix = os.path.join(self.tmp, "logs", "map_check")
        out, text = run_extensions([ext], path, prefix, ignore={"altitude": ext.cfg["ignore"]})
        self.assertEqual(out.count["altitude"], 0)
        self.assertGreater(out.suppressed[("altitude", "41")], 0)
        self.assertTrue(os.path.isfile(prefix + "_altitude.png"), text)
        self.assertIn("Trend chart: " + prefix + "_altitude.png", text)

    def test_altitude_window(self):
        """altitude isShow: clicking an abrupt point / lanelet in the top view window shows the elevation profile
        in the small detail window"""
        import matplotlib.pyplot as plt
        from matplotlib.backend_bases import MouseEvent

        path = os.path.join(self.tmp, "altitude.osm")  # the left boundary has a 2 m spike at x = 20
        left = {k + 1: (10.0 * k, 3.5, 0.2 * k + (2.0 if k == 2 else 0.0)) for k in range(6)}
        right = {k + 7: (10.0 * k, 0.0, 0.2 * k) for k in range(6)}
        write_osm(path, {**left, **right}, {31: tuple(left), 32: tuple(right)}, {41: (31, 32, "road", {})})
        ext = extmod.load(extmod.discover()["altitude"], {"plot": False, "isShow": True})
        _, text = run_extensions([ext], path)
        self.assertIn("Trend chart window", text)
        self.assertEqual(plt.get_figlabels(), ["MapChecker altitude: altitude.osm"])
        fig = plt.figure("MapChecker altitude: altitude.osm")
        fig.canvas.draw()
        ax = fig.axes[0]

        def click(x, y):
            """Click at coordinates (x, y) of the top view, return (terminal output, title of the longitudinal
            profile in the small detail window or None)"""
            px, py = ax.transData.transform((x, y))
            buf = io.StringIO()
            with contextlib.redirect_stdout(buf):
                for name in ("button_press_event", "button_release_event"):
                    fig.canvas.callbacks.process(name, MouseEvent(name, fig.canvas, px, py, button=1))
            detail = "MapChecker altitude detail"
            return buf.getvalue(), (plt.figure(detail).axes[0].get_title(loc="left")
                                    if detail in plt.get_figlabels() else None)

        printed, title = click(20, 3.5)
        self.assertIn("[WARNING] #1 spike at node 3", printed)
        self.assertEqual(title, "#1 spike +2.00 m · lanelet 41 left")
        printed, title = click(45, 1.75)  # inside lanelet 41, far from the spike
        self.assertIn("lanelet 41 (road): 50.0 m, elevation 0.00 ~ 2.40 m, +1.00 m from start to end, "
                      "abrupt points #1", printed)
        self.assertEqual(title, "lanelet 41")
        printed, title = click(45, 10)  # empty area: the small detail window is kept
        self.assertEqual((printed, title), ("", "lanelet 41"))
        self.assertEqual(len(plt.get_fignums()), 2)  # the same small detail window is reused

    def test_new_extension_from_template(self):
        """Create an extension by copying the template following ext/README.md: auto discovery, enable, --set, config check"""
        ext_dir = os.path.join(self.tmp, "ext")
        shutil.copytree(os.path.join(extmod.EXT_DIR, "_template"), os.path.join(ext_dir, "my_check"))
        available = extmod.discover(ext_dir)
        self.assertEqual(extmod.select(available), [])  # enable is false in the template
        self.write_ext(ext_dir, "my_check", None, "enable: true\n")
        available = extmod.discover(ext_dir)
        self.assertEqual(extmod.select(available), [available["my_check"]])

        ext = extmod.load(available["my_check"], {"required_tags": ["speed_limit", "one_way"]})
        out, text = run_extensions([ext], self.map_path)
        self.assertEqual(out.count["my_check"], 1)
        self.assertIn("lanelet 21: missing tag one_way", text)

        with self.assertRaisesRegex(ValueError, "unknown parameter"):
            extmod.load(extmod.discover(ext_dir)["my_check"], {"required_tag": ["x"]})
        with self.assertRaisesRegex(ValueError, "invalid config"):
            extmod.load(extmod.discover(ext_dir)["my_check"], {"required_tags": []})
        with self.assertRaisesRegex(ValueError, "unknown extension"):
            extmod.select(available, ["nope"])

    def test_helper_module_and_crash(self):
        """The entry script can relatively import helper modules in script/; when an extension crashes, an ERROR is
        reported and the following extensions run as usual"""
        ext_dir = os.path.join(self.tmp, "ext")
        self.write_ext(ext_dir, "broken", "def check(ctx, cfg, out):\n    raise RuntimeError('boom')\n")
        self.write_ext(ext_dir, "helped", "from ._helper import count_roads\n\n"
                                          "def check(ctx, cfg, out):\n    out.warn(f'{count_roads(ctx)} roads')\n")
        with open(os.path.join(ext_dir, "helped", "script", "_helper.py"), "w", encoding="utf-8") as f:
            f.write("def count_roads(ctx):\n    return len(ctx.vehicle)\n")

        available = extmod.discover(ext_dir)
        out, text = run_extensions([extmod.load(e) for e in extmod.select(available)], self.map_path)
        self.assertEqual(out.errors["broken"], 1)
        self.assertIn("RuntimeError: boom", text)
        self.assertIn("[WARNING] 1 roads", text)

    @staticmethod
    def write_ext(ext_dir, name, script=None, config="enable: true\n"):
        for sub in ("script", "config"):
            os.makedirs(os.path.join(ext_dir, name, sub), exist_ok=True)
        with open(os.path.join(ext_dir, name, "config", "config.yaml"), "w", encoding="utf-8") as f:
            f.write(config)
        if script is not None:
            with open(os.path.join(ext_dir, name, "script", f"check_{name}.py"), "w", encoding="utf-8") as f:
                f.write(script)

    def test_ignore_items(self):
        self.assertEqual(parse_items([614, -99865, {615: "reason"}, {616: None}], "x"),
                         {"614": "", "-99865": "", "615": "reason", "616": ""})
        self.assertEqual(parse_items({614: "a"}, "x"), {"614": "a"})
        with self.assertRaisesRegex(ValueError, "must be a list"):
            parse_items(614, "x")
        with self.assertRaisesRegex(ValueError, "invalid lanelet id"):
            parse_items(["abc"], "x")
        path = os.path.join(self.tmp, "ignore.yaml")
        with open(path, "w", encoding="utf-8") as f:
            f.write("all: [614]\ncrosswalk: [22: too wide]\n")
        self.assertEqual(load_ignore(path, ["crosswalk"]), [("all", "614", ""), ("crosswalk", "22", "too wide")])
        with self.assertRaisesRegex(ValueError, "unknown key 'crosswalk'"):
            load_ignore(path)

    def test_cli(self):
        cfg = os.path.join(self.tmp, "config.yaml")
        with open(cfg, "w", encoding="utf-8") as f:
            f.write(f"input: {self.map_path}\nignore_file: {self.tmp}/none.yaml\nlog: {{enabled: false}}\n"
                    "heatmap: {enabled: false}\nUsing_LR: false\n")

        def run(*args):
            return subprocess.run([sys.executable, os.path.join(BASE_DIR, "check_lanelet_map.py"), "-c", cfg,
                                   "--no-color", *args], capture_output=True, text=True)

        r = run("--only-ext", "crosswalk", "--set", "crosswalk.max_extension=0.5")
        self.assertEqual(r.returncode, 1, r.stderr)
        self.assertIn("crosswalk warnings:      1", r.stdout)
        self.assertNotIn("Check 1", r.stdout)
        r = run("--only-ext", "crosswalk", "--set", "crosswalk.max_extension=3")
        self.assertEqual(r.returncode, 0, r.stderr)
        r = run("--only-ext", "nope")
        self.assertEqual(r.returncode, 2)
        self.assertIn("unknown extension", r.stderr)
        r = run("--list-ext")
        self.assertEqual(r.returncode, 0)
        self.assertIn("crosswalk", r.stdout)


