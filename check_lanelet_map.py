#!/usr/bin/env python3
"""
Lanelet2 map checker

Checks:
  1. Turn signal (turn_direction): whether curve / turn lanelets, and straight lanelets intersecting other lanes, have
     turn_direction set
  2. Right of way (right_of_way): whether crossing / merging lanelets have right_of_way set;
     whether an existing right_of_way is referenced by the priority lanelet, and whether the two lanelets really overlap
     (red ERROR when they do not overlap at all)
  3. Autoware (when autoware_checking is true): runs utils/validate_autoware_map.py and merges its results,
     its turn_direction results are merged into Check 1 (each lanelet reported only once), the others
     (load / elevation / traffic_light) are reported in Check 3
  Extension checks (ext/<name>/): run after Checks 1~3 when enable is true in their config/config.yaml;
     --ext / --only-ext / --no-ext select the extensions to run, --list-ext lists all extensions.
     To write a new extension, see ext/README.md
Every WARNING / ERROR has an issue code <check>.<issue> ([WARNING stopline.polyline] ...), registered with its
severity (error / warning / off) and description in config/issue_codes.yaml for Checks 1~3, in
ext/<name>/config/issue_codes.yaml for each extension; the Summary counts the issues per code, and config/ignore.yaml
can ignore a single issue type with the code as key.
See config/config.yaml for the meaning of each parameter. Depends only on numpy and PyYAML; ROS needs to be sourced only
when autoware_checking is true, and matplotlib is needed only when heatmap.enabled is true.

When Using_LR is true, model_file (the logistic regression model generated by train_model.py) is used to score the
WARNINGs about missing turn_direction / right_of_way in Check 1 and Check 2 [WARNING p=0.93], p being the probability
that the warning is a true issue (fixed later). In each check these WARNINGs are output by descending p (Check 2 lists
all areas first, each entry notes the area it is in); WARNINGs / ERRORs without a score come before them.
Scoring only uses the numbers in the model, scikit-learn is not needed. See README.md for details.

Each run writes all its output files in a new directory of log.dir (logs/map_check_YYYYmmdd_HHMMSS/), named like it:
the log map_check_YYYYmmdd_HHMMSS.log, the heatmap .png, the masque and the files generated by extension checks.

When heatmap.enabled is true, the areas with the most issues (Hotspots) are listed at the end of the log, and a
heatmap .png with the same name is generated next to the log: the map is colored by issue density from blue (few)
to red (many), with these areas circled; when isShow is true, the heatmap window (utils/heatmap_window.py: map
never stretched by resizing, pan / zoom, layers, list of the hotspots and issues, details) pops up after the report
ends.
Extension checks can also create pyplot windows (e.g. isShow of altitude), which pop up together with the heatmap window.
When Using_LR is true, the heatmap and the areas are weighted by p (a scored WARNING counts as p, others count as 1),
i.e. they are ranked by the expected number of true issues.
When masque.enabled is also true, a slow-down masque with one detection_area per hotspot is written next to the log
(utils/masque.py), in the same format as the masque_lanelet2.osm of the map repositories.

Usage:
  python3 check_lanelet_map.py                      # uses config/config.yaml
  python3 check_lanelet_map.py -c other_config.yaml
  python3 check_lanelet_map.py some_map.osm --turn-angle 45   # command-line arguments take precedence over config.yaml
  python3 check_lanelet_map.py --only-ext crosswalk --set crosswalk.max_extension=1.0   # only run extension crosswalk
  python3 check_lanelet_map.py --masque             # also write the slow-down masque of the hotspots

Directory layout:
  MapChecker/
    check_lanelet_map.py   entry point
    config/config.yaml     configuration (relative paths in it are relative to MapChecker/)
    config/ignore.yaml     manually ignored lanelets
    config/issue_codes.yaml  issue codes of Checks 1~3 with their severity and description
    config/model.yaml      warning scoring model (generated by train_model.py)
    utils/                 map loading, geometry, topology, checks, output, features and model,
                           training data and training
    ext/                   extension checks, each with its own script/, config/ (config.yaml, issue_codes.yaml) and
                           README.md;
                           ext/_template/ is the template for new extensions
    train_model.py         builds training data from the git history of map repositories and trains a logistic
                           regression, generating config/model.yaml
    libs/                  third-party libraries installed by install.sh
"""

import argparse
import os
import sys
import time

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
# install.sh installs third-party libraries in libs/; put it first, ahead of the versions in system and user directories
sys.path.insert(0, os.path.join(BASE_DIR, "libs"))
# The matplotlib-*-nspkg.pth of system python3-matplotlib puts the system mpl_toolkits in sys.modules at Python startup,
# so matplotlib in libs/ imports the old system mpl_toolkits.mplot3d and fails (warning "Unable to import Axes3D"):
# give priority to the one in libs/
if "mpl_toolkits" in sys.modules:
    sys.modules["mpl_toolkits"].__path__.insert(0, os.path.join(BASE_DIR, "libs", "mpl_toolkits"))

import yaml

from utils import ext as extmod
from utils.checks import run_core_checks
from utils.config import DEFAULT_CONFIG_PATH, load_config
from utils.context import MapContext
from utils.heatmap import prepare_windows, report_hotspots, show_windows
from utils.ignore import ignore_by_category, load_ignore, report_ignored
from utils.issue_codes import IssueCodes
from utils.masque import check_config as check_masque_config
from utils.masque import report_masque
from utils.model import Model
from utils.printer import Printer


def run(map_path, opts, ignore_entries, ignore_path, out, core=True, validate_autoware=None, extensions=(),
        heatmap=None, output_prefix=None, masque=None):
    """
    core:              whether to run Checks 1~3 (False with --only-ext)
    validate_autoware: validate() of utils/validate_autoware_map.py, None means Check 3 is not run
    extensions:        extension checks to run (Extensions that went through load() in utils/ext.py)
    heatmap:           {"path", "radius", "top", "show"}, None means no heatmap is generated
    masque:            masque section of the config (utils.masque.check_config) and "path", None means no masque;
                       requires heatmap
    output_prefix:     path prefix of the log / heatmap (without extension); files generated by extension checks
                       (e.g. the altitude trend chart) are also named with it
    """
    ctx = MapContext.from_file(map_path, opts, output_prefix)
    out.info(f"Date: {time.strftime('%Y-%m-%d %H:%M:%S')}")
    out.info(f"Map: {os.path.abspath(map_path)}")
    out.info(f"Lanelets: {len(ctx.lanelets)}, regulatory elements: {len(ctx.reg_elems)}")
    if ctx.map.skipped:
        out.info("Lanelets not loaded (incomplete, not checked): "
                 + "; ".join(f"{lid} ({reason})" for lid, reason in ctx.map.skipped))
    if ctx.only_check_aoi and not ctx.aois:
        out.info("AOI: only_check_AOI is enabled but no AOI found in map, no check performed")
        return 0

    autoware = None
    if core:
        # The Autoware check runs first, its turn_direction results are merged with the geometric checks in Check 1
        autoware = validate_autoware(map_path) if validate_autoware else None
        run_core_checks(ctx, out, autoware)
    extmod.run_extensions(ctx, extensions, out)

    out.header("Summary")
    if core:
        out.info(f"turn_direction warnings: {out.count['turn_direction']}")
        out.info(f"right_of_way warnings:   {out.count['right_of_way']}")
        out.info(f"right_of_way errors:     {out.errors['right_of_way']}")
        if autoware:
            out.info(f"autoware warnings:       {out.count['autoware']}")
            out.info(f"autoware errors:         {out.errors['autoware']}")
    for ext in extensions:
        out.info(f"{ext.name + ' warnings:':<24} {out.count[ext.name]}")
        if out.errors[ext.name]:
            out.info(f"{ext.name + ' errors:':<24} {out.errors[ext.name]}")
    report_codes(out)
    scores = [i.p for i in out.issues if i.p is not None]
    if scores:
        out.info(f"scored warnings:         {len(scores)}, {sum(p < 0.5 for p in scores)} of them with p < 0.5 "
                 f"(likely false positives)")
    if out.total == 0:
        out.ok("No issue found")

    if heatmap:
        spots = report_hotspots(ctx.lanelets, ctx.aois if ctx.only_check_aoi else [], out, heatmap["path"],
                                heatmap["radius"], heatmap["top"], os.path.basename(map_path), heatmap["show"],
                                heatmap["min_p"])
        if masque:
            report_masque(masque["path"], spots, ctx, masque, out)
    report_ignored(ignore_entries, ignore_path, ctx, out)
    return out.total


def report_codes(out):
    """Number of issues per code in the Summary, in the order of the output, and the codes turned off"""
    if out.by_code:
        out.info("issues by code:")
        width = max(len(code) for code in out.by_code)
        for code, n in out.by_code.items():
            out.info(f"  {code:<{width}}  {out.codes.severity(code):<7} {n:>5}  {out.codes.title(code)}")
    if out.disabled:
        out.info("not reported (severity off): " + ", ".join(f"{code} {n}" for code, n in out.disabled.items()))


def _names(text):
    return [n.strip() for n in text.split(",") if n.strip()]


def parse_args():
    parser = argparse.ArgumentParser(description="Check turn_direction and right_of_way in a Lanelet2 map, "
                                                 "plus the extension checks in ext/")
    parser.add_argument("map", nargs="?", help="path to lanelet2_map.osm (overrides 'input' in config)")
    parser.add_argument("-c", "--config", help="config file, default: config/config.yaml next to this script")
    parser.add_argument("--turn-angle", type=float,
                        help="min heading change (deg) to consider a lanelet as a curve (overrides config)")
    parser.add_argument("--turn-window", type=float,
                        help="max arc length (m) over which the heading change is measured, so gentle bends "
                             "on long lanelets are ignored (overrides config)")
    parser.add_argument("--min-overlap-area", type=float,
                        help="min overlap area (m²) to consider two lanelets as overlapping (overrides config)")
    parser.add_argument("--parallel-min-length", type=float,
                        help="two straight lanelets overlapping over at least this length (m) whose centerlines stay "
                             "--parallel-min-gap apart are parallel lanes, not an overlap (overrides config)")
    parser.add_argument("--parallel-min-gap", type=float,
                        help="min distance (m) between the centerlines alongside the overlap for parallel lanes, "
                             "see --parallel-min-length (overrides config)")
    parser.add_argument("--ignore-isolated-turns", action=argparse.BooleanOptionalAction, default=None,
                        help="ignore curves that do not intersect any other lane (overrides config)")
    parser.add_argument("--straight-as-turn-light", action=argparse.BooleanOptionalAction, default=None,
                        help="count turn_direction=straight as a turn light setting (overrides config)")
    parser.add_argument("--only-check-aoi", action=argparse.BooleanOptionalAction, default=None,
                        help="only check lanelets fully inside the AOI of the map, no check is performed if the "
                             "map has no AOI (overrides config)")
    parser.add_argument("--autoware-checking", action=argparse.BooleanOptionalAction, default=None,
                        help="also run utils/validate_autoware_map.py and merge its results, requires ROS "
                             "(overrides config)")
    parser.add_argument("--ignore-file", help="file listing lanelets to ignore (overrides config)")
    parser.add_argument("--using-lr", action=argparse.BooleanOptionalAction, default=None,
                        help="score warnings with the logistic regression model (overrides Using_LR in config)")
    parser.add_argument("--model-file", help="model generated by train_model.py, used when Using_LR is true "
                                             "(overrides config)")
    parser.add_argument("--map-min-p", type=float,
                        help="with Using_LR, scored warnings with p below this are not shown in the heatmap, the report "
                             "still lists them (overrides config)")
    parser.add_argument("--heatmap", action=argparse.BooleanOptionalAction, default=None,
                        help="list the areas with the most issues and save a heatmap image next to the log, "
                             "requires matplotlib (overrides heatmap.enabled in config)")
    parser.add_argument("--show-heatmap", action=argparse.BooleanOptionalAction, default=None,
                        help="pop up the heatmap in a window after the report, only when the heatmap is generated "
                             "(overrides isShow in config)")
    parser.add_argument("--masque", action=argparse.BooleanOptionalAction, default=None,
                        help="write a slow-down masque (one detection_area per hotspot) next to the log, requires "
                             "the heatmap (overrides masque.enabled in config)")
    parser.add_argument("--no-color", action="store_true", help="disable colored output")

    group = parser.add_argument_group("extension checks (ext/<NAME>/, see ext/README.md)")
    which = group.add_mutually_exclusive_group()
    which.add_argument("--ext", type=_names, metavar="NAME[,NAME...]",
                       help="run these extensions instead of the enabled ones (regardless of 'enable')")
    which.add_argument("--only-ext", type=_names, metavar="NAME[,NAME...]",
                       help="run only these extensions (regardless of 'enable'), skip checks 1~3")
    which.add_argument("--no-ext", action="store_true", help="run no extension")
    group.add_argument("--set", action="append", metavar="NAME.KEY=VALUE",
                       help="override a parameter in the config of an extension, e.g. crosswalk.max_extension=1.0 "
                            "(repeatable)")
    group.add_argument("--list-ext", action="store_true", help="list the extensions and exit")
    return parser, parser.parse_args()


def new_run_dir(log_dir):
    """Directory of this run's output files in log_dir: map_check_YYYYmmdd_HHMMSS, with a suffix _2, _3, ... when it
    already exists (runs started in the same second); not created here, only when a file is written in it"""
    name = time.strftime("map_check_%Y%m%d_%H%M%S")
    path, n = os.path.join(log_dir, name), 1
    while os.path.exists(path):
        n += 1
        path = os.path.join(log_dir, f"{name}_{n}")
    return path


def list_extensions(available):
    if not available:
        print(f"No extension in {extmod.EXT_DIR}")
    for ext in available.values():
        status = "enabled" if ext.enabled else "template" if ext.name.startswith("_") else "disabled"
        print(f"{ext.name:20s} {status:9s} {ext.title}")


def main():
    parser, args = parse_args()
    try:
        available = extmod.discover()
    except (OSError, ValueError, yaml.YAMLError) as e:
        parser.error(f"invalid extension: {e}")
    if args.list_ext:
        list_extensions(available)
        return 0

    config_path = args.config or DEFAULT_CONFIG_PATH
    if not os.path.isfile(config_path):
        parser.error(f"config file not found: {config_path}")
    cfg = load_config(config_path)
    map_path = args.map or cfg["input"]
    if not os.path.isfile(map_path):
        parser.error(f"map file not found: {map_path}")
    try:
        # codes of Checks 1~3, and of every extension (ignore.yaml can use them even if the extension is not run)
        codes = extmod.register_codes(IssueCodes.load(cfg["issue_codes_file"]), available.values())
    except (OSError, ValueError, yaml.YAMLError) as e:
        parser.error(f"invalid issue codes file: {e}")
    ignore_path = os.path.abspath(args.ignore_file or cfg["ignore_file"])
    if args.ignore_file and not os.path.isfile(ignore_path):
        parser.error(f"ignore file not found: {args.ignore_file}")
    try:
        # besides all and Checks 1~3, ignore.yaml can also contain ignore lists named after extension checks, and
        # ignore lists of a single issue type named after its code
        ignore_entries = load_ignore(ignore_path, available, codes.codes)
    except (ValueError, yaml.YAMLError) as e:
        parser.error(str(e))

    # command-line arguments take precedence over config.yaml
    cli = {
        "turn_angle": args.turn_angle,
        "turn_window": args.turn_window,
        "min_overlap_area": args.min_overlap_area,
        "parallel_min_length": args.parallel_min_length,
        "parallel_min_gap": args.parallel_min_gap,
        "ignore_isolated_turns": args.ignore_isolated_turns,
        "straight_as_turn_light": args.straight_as_turn_light,
        "only_check_AOI": args.only_check_aoi,
        "autoware_checking": args.autoware_checking,
        "Using_LR": args.using_lr,
    }
    opts = {k: cfg[k] if v is None else v for k, v in cli.items()}
    core = not args.only_ext

    # Extension checks: run those with enable true by default; ignore in their config is scoped to the extension name
    try:
        extensions = extmod.select(available, [] if args.no_ext else args.only_ext or args.ext)
        overrides = extmod.parse_overrides(args.set)
        not_run = [n for n in overrides if n not in {ext.name for ext in extensions}]
        if not_run:
            raise ValueError(f"--set: extension {', '.join(not_run)} is not run (enable it, or use --ext)")
        for ext in extensions:
            extmod.load(ext, overrides.get(ext.name))
    except (OSError, ValueError, yaml.YAMLError) as e:
        parser.error(f"invalid extension: {e}")
    ignore_entries += [(ext.name, lid, reason) for ext in extensions for lid, reason in ext.cfg["ignore"].items()]

    model = None
    if core and opts["Using_LR"]:
        model_path = os.path.abspath(args.model_file) if args.model_file else cfg["model_file"]
        if not model_path or not os.path.isfile(model_path):
            parser.error(f"Using_LR requires a model file (not found: {model_path}), "
                         f"run train_model.py first, or run with --no-using-lr")
        try:
            model = Model(model_path)
        except (ValueError, KeyError, yaml.YAMLError) as e:
            parser.error(f"invalid model file: {e}")

    validate_autoware = None
    if core and opts["autoware_checking"]:
        try:
            from utils.validate_autoware_map import validate as validate_autoware
        except ImportError as e:
            parser.error(f"autoware_checking requires ROS ({e}), or run with --no-autoware-checking")

    heatmap = None
    if cfg["heatmap"]["enabled"] if args.heatmap is None else args.heatmap:
        try:
            import matplotlib  # noqa: F401
        except ImportError as e:
            parser.error(f"heatmap requires matplotlib ({e}), or run with --no-heatmap")
        min_p = float(cfg["map_min_p"] if args.map_min_p is None else args.map_min_p)
        if not 0.0 <= min_p <= 1.0:
            parser.error(f"map_min_p must be between 0 and 1, got {min_p}")
        heatmap = {"radius": float(cfg["heatmap"]["radius"]), "top": int(cfg["heatmap"]["top"]),
                   "show": bool(cfg["isShow"] if args.show_heatmap is None else args.show_heatmap), "min_p": min_p}
        if heatmap["show"]:
            prepare_windows()  # windows of extension checks (e.g. isShow of altitude) open with the heatmap window

    masque = None
    if cfg["masque"]["enabled"] if args.masque is None else args.masque:
        if not heatmap:
            parser.error("the masque is made from the hotspots: it requires the heatmap (heatmap.enabled or --heatmap), "
                         "or run with --no-masque")
        try:
            masque = check_masque_config(cfg["masque"])
        except ValueError as e:
            parser.error(f"invalid masque config: {e}")

    # the log, the heatmap, the masque and the files generated by extension checks share the same name, in a new
    # directory of the log directory for this run
    run_dir = new_run_dir(cfg["log"]["dir"])
    stamp = os.path.join(run_dir, os.path.basename(run_dir))
    if cfg["log"]["enabled"] or heatmap:
        os.makedirs(run_dir, exist_ok=True)
    if heatmap:
        heatmap["path"] = stamp + ".png"
    if masque:
        masque["path"] = stamp + "_masque.osm"
    log_file = log_path = None
    if cfg["log"]["enabled"]:
        log_path = stamp + ".log"
        log_file = open(log_path, "w", encoding="utf-8")

    # checks that are run; ignore list entries of other checks are marked as check not run at the end of the report
    categories = (("turn_direction", "right_of_way") + (("autoware",) if validate_autoware else ()) if core else ()) \
        + tuple(ext.name for ext in extensions)
    out = Printer(not args.no_color and sys.stdout.isatty(), log_file, ignore_by_category(ignore_entries, categories),
                  model, codes)
    try:
        total = run(map_path, opts, ignore_entries, ignore_path, out, core, validate_autoware, extensions, heatmap,
                    stamp, masque)
    finally:
        if log_file:
            log_file.close()
            print(f"\nLog saved to: {log_path}")
        if heatmap and os.path.isfile(heatmap["path"]):
            print(f"Heatmap saved to: {heatmap['path']}")
        if masque and os.path.isfile(masque["path"]):
            print(f"Masque saved to: {masque['path']}")
    # heatmap (isShow) and windows created by extension checks (e.g. isShow of altitude) pop up together after the report
    show_windows()
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main())
