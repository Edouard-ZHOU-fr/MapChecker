"""
One map plus the results shared by the checks, passed to check(ctx, cfg, out) of Check 1~3 and extension checks (ext/).
Overlaps, topology, etc. are only computed when needed, and cached for reuse by later checks.
"""

from functools import cached_property

import numpy as np

from .geometry import lanelets_in_aoi
from .lanelet_map import by_id, load_map
from .topology import build_topology, find_overlaps


class MapContext:
    """
    map:       utils.lanelet_map.LaneletMap, everything in the map file (also meta, attrib, extra, skipped, projected);
               the following are its attributes of the same name:
    lanelets:  {id: utils.lanelet_map.Lanelet}, including non-vehicle lanelets such as crosswalk
    reg_elems: {id: utils.lanelet_map.RegElem}
    aois:      list of AOI polygons in the map
    nodes / ways / relations: all <node> / <way> / <relation>: {id: Node / Way / Relation}
    opts:      check parameters (config/config.yaml merged with command-line arguments), e.g. opts["min_overlap_area"]
    map_path:  map file path (None when read from memory)
    output_prefix: path prefix of this run's output files (log, heatmap), e.g. logs/map_check_20261021_141000;
               other files generated by extension checks (e.g. figures) are named f"{output_prefix}_{name}.png".
               None (e.g. in tests): no files are generated
    """

    def __init__(self, lanelet_map, opts, map_path=None, output_prefix=None):
        self.map = lanelet_map
        self.lanelets = lanelet_map.lanelets
        self.reg_elems = lanelet_map.reg_elems
        self.aois = lanelet_map.aois
        self.nodes = lanelet_map.nodes
        self.ways = lanelet_map.ways
        self.relations = lanelet_map.relations
        self.opts = opts
        self.map_path = map_path
        self.output_prefix = output_prefix
        self._in_aoi = {}

    @classmethod
    def from_file(cls, map_path, opts, output_prefix=None):
        return cls(load_map(map_path), opts, map_path, output_prefix)

    @property
    def only_check_aoi(self):
        """If True, only lanelets entirely inside the AOI are checked (see in_aoi / select)"""
        return bool(self.opts.get("only_check_AOI"))

    @cached_property
    def vehicle(self):
        """Vehicle lanelets {id: Lanelet} (subtype is road / highway / road_shoulder)"""
        return {k: v for k, v in self.lanelets.items() if v.is_vehicle}

    def by_subtype(self, *subtypes):
        """Lanelets {id: Lanelet} whose subtype is one of subtypes, e.g. ctx.by_subtype("crosswalk")"""
        return {k: v for k, v in self.lanelets.items() if v.subtype in subtypes}

    @cached_property
    def topology(self):
        """Predecessor / successor relations (succ, pred), both {lanelet id: set of successor / predecessor lanelet ids}"""
        return build_topology(self.lanelets)

    @cached_property
    def overlaps(self):
        """
        Geometrically overlapping vehicle lanelet pairs (excluding consecutive and adjacent ones), always computed on
        the whole map: [(a_id, b_id, rel, area m², overlap center [x, y], overlap length along the principal direction m)],
        rel is None (crossing) / "merge" / "diverge"
        """
        return find_overlaps(self.lanelets, self.opts["min_overlap_area"], self.opts["min_overlap_width"],
                             topology=self.topology)

    def in_aoi(self, lanelet_id):
        """
        Whether the lanelet is in the check scope: always True if only_check_AOI is false, otherwise it must be
        entirely inside the AOI
        """
        if not self.only_check_aoi:
            return True
        if lanelet_id not in self._in_aoi:
            ll = self.lanelets.get(lanelet_id)
            self._in_aoi[lanelet_id] = ll is not None and bool(lanelets_in_aoi({lanelet_id: ll}, self.aois))
        return self._in_aoi[lanelet_id]

    def select(self, lanelets):
        """The lanelets in lanelets ({id: Lanelet}) that are in the check scope (see in_aoi)"""
        return {k: v for k, v in lanelets.items() if self.in_aoi(k)}

    def vehicle_near(self, points):
        """
        Vehicle lanelets whose bounding box intersects the bounding box of points ([N, 2], e.g. a lanelet's polygon),
        sorted by id; used for coarse filtering before the exact computation
        """
        lo, hi = np.min(points, axis=0), np.max(points, axis=0)
        sel = np.nonzero((self._vehicle_bbox[:, 0] <= hi[0]) & (self._vehicle_bbox[:, 2] >= lo[0])
                         & (self._vehicle_bbox[:, 1] <= hi[1]) & (self._vehicle_bbox[:, 3] >= lo[1]))[0]
        return [self._vehicle_sorted[i] for i in sel]

    @cached_property
    def _vehicle_sorted(self):
        return sorted(self.vehicle.values(), key=by_id)

    @cached_property
    def _vehicle_bbox(self):
        return np.array([np.r_[ll.polygon.min(axis=0), ll.polygon.max(axis=0)]
                         for ll in self._vehicle_sorted]).reshape(-1, 4)
