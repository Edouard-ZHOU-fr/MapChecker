"""
Train the warning scoring model (logistic regression), generate config/model.yaml; called by train_model.py

Reads the labeled warnings in the data/*.csv generated by utils/build_dataset.py and trains one model per check
(turn_direction / right_of_way):
  p = sigmoid(intercept + Σ coef * (x - mean) / scale),
  p being the probability that the warning is a true issue (fixed later)

Repositories with only one label (e.g. all warnings were fixed) are not used for training: they cannot tell which
warnings in the same map get fixed, and would only make the model learn the difference of "which map".

The coefficients of the features listed in NEGATIVE_FEATURES in utils/features.py (domain knowledge: the larger the
value, the more likely a false positive) are constrained to <= 0: the sign is decided by domain knowledge, the magnitude
by the data. sklearn's LogisticRegression does not support constraining coefficients, so scipy's L-BFGS-B is used here
to solve the same objective function (L2 regularization, class_weight=balanced), just with bounds on the coefficients.

Evaluation uses leave-one-map-out cross-validation: each time one repository is held out, the model is trained on the
other repositories and then scores the warnings of the held-out repository, which amounts to testing the model on a
new map. The AUC of ranking by a single feature alone is also listed, to see whether the model is more useful than
simple rules.
AUC: probability that, for a randomly picked true issue and false positive, the true issue gets the higher score;
0.5 equals random guessing, 1 is perfect ranking.

Only training needs scikit-learn; scoring in check_lanelet_map.py only uses the numbers in config/model.yaml.
"""

import csv
import os
import time

import numpy as np
import yaml
from scipy.optimize import minimize
from scipy.special import expit
from sklearn.base import BaseEstimator, ClassifierMixin
from sklearn.metrics import roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from utils.features import FEATURES, NEGATIVE_FEATURES

MIN_PER_CLASS = 10  # minimum number of samples needed for each label


def load_samples(path, features):
    with open(path, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["label"] in ("0", "1")]
    x = np.array([[float(r[name]) for name in features] for r in rows]).reshape(-1, len(features))
    y = np.array([int(r["label"]) for r in rows])
    groups = np.array([r["repo"] for r in rows])
    return x, y, groups


class SignedLogisticRegression(BaseEstimator, ClassifierMixin):
    """
    Same objective function as LogisticRegression(C=C, class_weight="balanced"):
      min 0.5 * |w|² + C * Σ sample weight * log loss
    upper: upper bound of each coefficient (None means unbounded, 0 means coefficient <= 0)
    class_weight="balanced": when the two classes have different sample counts, weight them proportionally so that the
    model does not favor the larger class
    """

    def __init__(self, C=1.0, upper=None):
        self.C = C
        self.upper = upper

    def fit(self, x, y):
        sw = (len(y) / (2.0 * np.bincount(y, minlength=2)))[y]

        def objective(theta):
            w, b = theta[:-1], theta[-1]
            z = x @ w + b
            g = self.C * sw * (expit(z) - y)
            loss = 0.5 * w @ w + self.C * np.sum(sw * (np.logaddexp(0.0, z) - y * z))
            return loss, np.r_[w + x.T @ g, g.sum()]

        upper = self.upper or [None] * x.shape[1]
        bounds = [(None, u) for u in upper] + [(None, None)]  # intercept unbounded
        theta = minimize(objective, np.zeros(x.shape[1] + 1), jac=True, method="L-BFGS-B", bounds=bounds).x
        self.coef_, self.intercept_, self.classes_ = theta[None, :-1], theta[-1:], np.array([0, 1])
        return self

    def predict_proba(self, x):
        p = expit(x @ self.coef_[0] + self.intercept_[0])
        return np.c_[1.0 - p, p]


def make_model(category, c):
    negative = NEGATIVE_FEATURES.get(category, ())
    upper = [0.0 if name in negative else None for name in FEATURES[category]]
    return make_pipeline(StandardScaler(), SignedLogisticRegression(C=c, upper=upper))


def auc(y, score):
    return roc_auc_score(y, score)


def best_single_feature(x, y):
    """Single feature with the highest AUC: (AUC, column, direction), direction -1 means smaller values are more
    likely true issues"""
    return max((max(a, 1 - a), j, 1 if a >= 0.5 else -1) for j in range(x.shape[1]) for a in [auc(y, x[:, j])])


def leave_one_map_out(category, x, y, groups, c):
    """
    Each time, hold out one repository, train on the other repositories, then score it.
    Returns ({repository: (model AUC, single-feature baseline AUC, baseline feature column)}, out-of-fold probability
    of each sample); the single-feature baseline also chooses feature and direction using only the other repositories
    """
    result, oof = {}, np.empty(len(y))
    for repo in np.unique(groups):
        test, train = groups == repo, groups != repo
        oof[test] = make_model(category, c).fit(x[train], y[train]).predict_proba(x[test])[:, 1]
        _, j, sign = best_single_feature(x[train], y[train])
        result[repo] = (auc(y[test], oof[test]), auc(y[test], sign * x[test, j]), j)
    return result, oof


def train(category, x, y, groups, c):
    features = FEATURES[category]
    print(f"\n=== {category} ===")
    one_label = [r for r in np.unique(groups) if len(np.unique(y[groups == r])) < 2]
    if one_label:
        print(f"Excluded (only one label): {', '.join(f'{r} ({(groups == r).sum()})' for r in one_label)}")
        keep = ~np.isin(groups, one_label)
        x, y, groups = x[keep], y[keep], groups[keep]
    print(f"{len(y)} samples, {y.sum()} label 1 (fixed), {len(y) - y.sum()} label 0 (false positive)")
    if min(y.sum(), len(y) - y.sum()) < MIN_PER_CLASS or len(np.unique(groups)) < 2:
        print(f"Skipped: need at least {MIN_PER_CLASS} samples of each label in at least 2 repositories")
        return None

    per_repo, oof = leave_one_map_out(category, x, y, groups, c)
    print("Leave-one-map-out (each repository scored by a model trained on the others):")
    for repo, (a, b, j) in per_repo.items():
        m = groups == repo
        print(f"  {repo:36s} {m.sum():4d} samples, {y[m].sum():4d} label 1   "
              f"model AUC {a:.2f}   best single feature AUC {b:.2f} ({features[j]})")
    cv_auc, base_auc = np.mean([v[0] for v in per_repo.values()]), np.mean([v[1] for v in per_repo.values()])
    print(f"  {'mean of repositories':36s} {'':33s}model AUC {cv_auc:.2f}   best single feature AUC {base_auc:.2f}")
    low = oof < 0.5
    print(f"  with p < 0.5 as false positive: {(low & (y == 0)).sum()}/{(y == 0).sum()} false positives caught, "
          f"{(low & (y == 1)).sum()}/{(y == 1).sum()} real issues wrongly scored low")

    model = make_model(category, c).fit(x, y)
    scaler, lr = model[0], model[-1]
    negative = NEGATIVE_FEATURES.get(category, ())
    print("Coefficients (standardized, + means more likely real issue):")
    for w, name in sorted(zip(lr.coef_[0], features), key=lambda t: -abs(t[0])):
        note = ""
        if name in negative:
            note = "  (constrained <= 0" + (", at the bound: the data does not support lowering p)" if w > -1e-4 else ")")
        print(f"  {name:20s} {w:+.2f}{note}")
    return {
        "features": list(features),
        "mean": [round(float(v), 6) for v in scaler.mean_],
        "scale": [round(float(v), 6) for v in scaler.scale_],
        "coef": [round(float(v), 6) for v in lr.coef_[0]],
        "intercept": round(float(lr.intercept_[0]), 6),
        "min": [round(float(v), 6) for v in x.min(axis=0)],  # value range of the training data, see utils/model.py
        "max": [round(float(v), 6) for v in x.max(axis=0)],
        "samples": int(len(y)),
        "positives": int(y.sum()),
        "cv_auc": round(float(cv_auc), 3),
    }


def train_models(data_dir, output, c=1.0):
    """Train the model of each check on the training data in data_dir and save them to output; c is the inverse of the
    regularization strength. Returns True if a model was saved"""
    result = {"trained": time.strftime("%Y-%m-%d %H:%M:%S")}
    for category, features in FEATURES.items():
        path = os.path.join(data_dir, f"{category}.csv")
        if not os.path.isfile(path):
            print(f"{path} not found, run train_model.py without --skip-build first")
            continue
        m = train(category, *load_samples(path, features), c)
        if m:
            result[category] = m

    if len(result) == 1:
        print("\nNo model trained")
        return False
    with open(output, "w", encoding="utf-8") as f:
        f.write("# Generated by train_model.py, do not edit manually\n"
                "# p = 1 / (1 + exp(-(intercept + Σ coef * (x - mean) / scale))), "
                "p is the probability that the warning is a true issue (fixed later)\n"
                "# Feature meanings: see utils/features.py; cv_auc is the leave-one-map-out cross-validation AUC\n")
        yaml.safe_dump(result, f, sort_keys=False, default_flow_style=None, allow_unicode=True)
    print(f"\nModel saved to: {output}")
    return True
